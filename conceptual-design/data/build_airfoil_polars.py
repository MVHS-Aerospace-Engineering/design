"""
Generate 2-D airfoil polars at RC Reynolds numbers with NeuralFoil and save
them as CSV so the sizing loop does not depend on NeuralFoil at run time.

Run from the repo root (only needed when the airfoil list or n_crit changes):
    .venv/bin/python conceptual-design/data/build_airfoil_polars.py

Why NeuralFoil instead of Raymer's flat-plate skin friction for the wing:
at Re ~ 1e5 laminar separation bubbles dominate profile drag, and Raymer's
methods are calibrated for full-size aircraft (Re ~ 1e6-1e7). NeuralFoil is a
learned surrogate of XFOIL, which is the standard tool for this regime.
Cross-check against UIUC low-speed wind-tunnel data (Selig et al.) is
recommended in preliminary design.
"""
import csv
import os
import sys

import numpy as np

import aerosandbox as asb
import neuralfoil as nf

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
from parameters import P  # noqa: E402

WING_AIRFOILS = ["sd7062", "sd7037", "e387", "s4083", "clarky", "naca4412"]
TAIL_AIRFOILS = ["naca0009"]
RE_GRID = [30e3, 50e3, 75e3, 100e3, 150e3, 200e3, 300e3, 500e3, 800e3]
ALPHA_GRID = np.arange(-8.0, 18.01, 0.25)


def polygon_area(xy):
    x, y = xy[:, 0], xy[:, 1]
    return 0.5 * abs(np.dot(x, np.roll(y, 1)) - np.dot(y, np.roll(x, 1)))


def main():
    out_dir = os.path.join(HERE, "airfoils")
    os.makedirs(out_dir, exist_ok=True)
    geo_rows = []
    for name in WING_AIRFOILS + TAIL_AIRFOILS:
        af = asb.Airfoil(name)
        coords = af.coordinates
        geo_rows.append({"name": name,
                         "t_c": round(float(af.max_thickness()), 5),
                         "area_ratio": round(polygon_area(coords), 5),
                         "role": "tail" if name in TAIL_AIRFOILS else "wing"})
        rows = []
        for re in RE_GRID:
            a = nf.get_aero_from_coordinates(coords, alpha=ALPHA_GRID, Re=re,
                                             n_crit=P.n_crit, model_size="xlarge")
            for i, al in enumerate(ALPHA_GRID):
                rows.append([re, round(float(al), 3), float(a["CL"][i]),
                             float(a["CD"][i]), float(a["CM"][i]),
                             float(a["analysis_confidence"][i])])
        with open(os.path.join(out_dir, f"{name}.csv"), "w", newline="") as f:
            w = csv.writer(f)
            w.writerow(["re", "alpha_deg", "cl", "cd", "cm", "confidence"])
            for r in rows:
                w.writerow([f"{v:.6g}" for v in r])
        print(f"{name}: t/c={geo_rows[-1]['t_c']:.3f}  {len(rows)} points")
    with open(os.path.join(out_dir, "geometry.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["name", "t_c", "area_ratio", "role"])
        w.writeheader()
        w.writerows(geo_rows)
    with open(os.path.join(out_dir, "README.md"), "w") as f:
        f.write("Generated by build_airfoil_polars.py with NeuralFoil "
                f"(model_size=xlarge, n_crit={P.n_crit}). Do not edit by hand.\n")


if __name__ == "__main__":
    main()
